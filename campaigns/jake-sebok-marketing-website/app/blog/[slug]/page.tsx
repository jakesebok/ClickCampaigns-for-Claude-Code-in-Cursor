import type { Metadata } from "next";
import Link from "next/link";
import Script from "next/script";
import { notFound } from "next/navigation";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { getAllPostSlugs, getPost } from "@/lib/blog";

interface Params {
  params: Promise<{ slug: string }>;
}

export function generateStaticParams() {
  return getAllPostSlugs().map((slug) => ({ slug }));
}

export async function generateMetadata({ params }: Params): Promise<Metadata> {
  const { slug } = await params;
  const post = getPost(slug);
  if (!post) return { title: "Not found" };
  const canonical = `https://jakesebok.com/blog/${post.slug}`;
  return {
    title: `${post.title} | Jake Sebok`,
    description: post.excerpt,
    keywords: post.keywords,
    alternates: { canonical },
    openGraph: {
      title: post.title,
      description: post.excerpt,
      url: canonical,
      type: "article",
      publishedTime: post.published_at,
      modifiedTime: post.modified_at,
      authors: ["Jake Sebok"]
    },
    twitter: {
      card: "summary_large_image",
      title: post.title,
      description: post.excerpt
    }
  };
}

export default async function BlogPostPage({ params }: Params) {
  const { slug } = await params;
  const post = getPost(slug);
  if (!post) notFound();

  return (
    <>
      {/* schema.org BlogPosting JSON-LD generated by the LocalCraft
          publish pipeline; inlined here verbatim for AI crawlers + Google AI Overviews. */}
      <Script
        id={`schema-article-${post.slug}`}
        type="application/ld+json"
        strategy="afterInteractive"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(post.schema_article) }}
      />
      {post.schema_faqpage && (
        <Script
          id={`schema-faqpage-${post.slug}`}
          type="application/ld+json"
          strategy="afterInteractive"
          dangerouslySetInnerHTML={{ __html: JSON.stringify(post.schema_faqpage) }}
        />
      )}

      <main className="px-6 lg:px-10 py-12 lg:py-20">
        <div className="max-w-[760px] mx-auto">
          <Link
            href="/blog"
            className="text-[12px] uppercase tracking-[0.12em] text-slate-500 hover:text-amber-700"
          >
            ← All notes
          </Link>

          <header className="mt-6 mb-10 pb-8 border-b border-slate-200">
            <p className="text-[12.5px] text-slate-500 mb-3">
              {new Date(post.published_at).toLocaleDateString("en-US", {
                year: "numeric",
                month: "long",
                day: "numeric"
              })}
            </p>
            <h1 className="font-cormorant text-[clamp(34px,5vw,52px)] leading-[1.1] tracking-[-0.01em] text-slate-900">
              {post.title}
            </h1>
            {post.excerpt && (
              <p className="mt-5 text-[18px] leading-relaxed text-slate-700">
                {post.excerpt}
              </p>
            )}
          </header>

          {post.hero_image_url && (
            <figure className="mb-10 -mx-6 sm:mx-0">
              <img
                src={post.hero_image_url}
                alt={post.title}
                width={1536}
                height={1024}
                loading="eager"
                style={{
                  width: "100%",
                  aspectRatio: "1536 / 1024",
                  objectFit: "cover",
                  borderRadius: 8,
                  display: "block"
                }}
              />
            </figure>
          )}

          <article className="blog-prose">
            <ReactMarkdown remarkPlugins={[remarkGfm]}>{post.body}</ReactMarkdown>
          </article>

          {post.faq.length > 0 && (
            <section className="mt-16 pt-10 border-t border-slate-200">
              <h2 className="font-cormorant text-[clamp(24px,3vw,32px)] leading-tight mb-6 text-slate-900">
                Common questions
              </h2>
              <dl className="space-y-6">
                {post.faq.map((f, i) => (
                  <div key={i}>
                    <dt className="font-medium text-[17px] text-slate-900">{f.q}</dt>
                    <dd className="mt-2 text-[16px] leading-relaxed text-slate-700">{f.a}</dd>
                  </div>
                ))}
              </dl>
            </section>
          )}
        </div>
      </main>
    </>
  );
}
